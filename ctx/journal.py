# retiring
# --------------------------------------------------------------------------- #

def prune(layout, config, before=None, archive=True):
    """Fold day files older than `before` into one archive per month.

    One committed file per active day per author, forever, means hundreds a
    year in every clone and every diff. Rolling them up keeps the history — the
    digest is a tail, so it is unaffected either way — while collapsing the
    file count. Per-author files and the legacy unattributed ones retire the
    same way, merged into one section per day.

    Returns (folded_paths, archive_paths).
    """
    if before is None:
        keep = int((config.get("journal") or {}).get("keep_days", 0) or 0)
        if keep <= 0:
            return [], []
        before = datetime.date.today() - datetime.timedelta(days=keep)

    by_month = {}
    for day_name, author, path in _day_files(layout):
        day = datetime.date.fromisoformat(day_name)
        if day >= before:
            continue
        by_month.setdefault(day.strftime("%Y-%m"), {}).setdefault(day, []) \
            .append((author, path))

    folded, archives = [], []
    for month in sorted(by_month):
        days = by_month[month]
        target = layout.journal / f"archive-{month}.md"
        lines = []
        if target.is_file():
            lines.append(target.read_text(encoding="utf-8").rstrip("\n"))
        else:
            lines.append(f"# {month} — archived journal")
        for day in sorted(days):
            # Read each day whole: the files are unlinked below, so a tail read
            # here would not fold the history, it would delete it.
            entries = _day_entries(days[day], limit=None)
            if entries:
                lines.append("")
                lines.append(f"## {day.isoformat()}")
                lines.extend(entries)

        if archive:
            try:
                # Atomic, because this file is the *only* copy of every month
                # an earlier prune already folded into it — the day files it
                # came from were unlinked then. A plain `write_text` truncates
                # first, so a crash mid-write destroys history with no source
                # left to rebuild it from.
                atomic.write_text(target, "\n".join(lines) + "\n")
            except OSError:
                # The archive did not land. Leave this month's day files alone:
                # an unwritten archive plus deleted inputs is the total-loss
                # case, and keeping them means the next run simply retries.
                continue
            archives.append(target)

        for day in sorted(days):
            for _author, path in days[day]:
                try:
                    path.unlink()
                except OSError:
                    pass
                folded.append(path)
    return folded, archives


def write_digest(layout, config):
    """Regenerate DIGEST.md. Deterministic given the journal contents."""
    lines = int((config.get("journal") or {}).get("digest_lines", 12))
    entries, earlier = tail(layout, lines)
    body = [DIGEST_HEADER, "", _DIGEST_NOTE, ""]
    if entries:
        body += [f"- {entry}" for entry in entries]
        body.append("")
        body.append(
            f"_{len(entries)} shown"
            + (f" · {earlier} earlier entries in journal/_" if earlier else "_")
        )
    else:
        body.append("_no entries yet_")
    # Atomic for the same reason as the archive, with one more: the digest is
    # read by SessionStart on every session, so a torn one is read immediately.
    atomic.write_text(layout.digest, "\n".join(body) + "\n")
    return layout.digest
