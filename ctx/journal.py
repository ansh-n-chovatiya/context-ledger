"""The append-only journal, and the mechanical digest read back from it.

Two properties matter more than anything else here:

* Writes inject nothing into the model's context. They cost disk, not tokens.
* The digest is a *tail*, not a summary. Reading it costs the same on a
  three-year-old repo as on a fresh one, and it never makes a model call.
  Semantic compression is `ctx digest --semantic`, which is explicit and rare.

Entries are pipe-delimited so they diff cleanly in a pull request and parse
with a `split`. Files are partitioned twice over: by date, and by *author*.
Date alone was not enough — two people working one repo on one day both
appended to `journal/2026-09-10.md` and both regenerated `DIGEST.md`, so they
conflicted on nearly every merge. An author writes only to their own file, and
every reader merges the files back into one time-ordered stream.

Day files in the pre-author shape (`journal/YYYY-MM-DD.md`) are still read, as
one unattributed stream alongside the per-author files. They are never
rewritten into the new shape: they record no author at all, so "migrating"
them would stamp every historical entry with whoever happened to run the
migration. An unattributed entry is honest; a wrongly attributed one is not.
"""

import datetime
import hashlib
import os
import subprocess

from . import atomic, redact

SEP = " | "
# How much of a day file the read path looks at. The digest is a tail, so the
# bound is what keeps SessionStart flat: 44 ms at 100k entries, and the same on
# a three-year-old repo as on a fresh one. It is a *read* bound only — a caller
# that destroys what it does not read must pass `limit=None`.
TAIL_BYTES = 64 * 1024
DIGEST_HEADER = "# Ledger digest"
_DIGEST_NOTE = "<!-- mechanical tail of journal/, regenerated by ctx; safe to delete -->"

# Separates the date from the author key in a day file name. Two characters, so
# it cannot be produced by the slug (which collapses runs of `-`) and a legacy
# name can never be mistaken for an attributed one.
AUTHOR_SEP = "--"
# An explicit override, for a machine account or a test that needs a known
# author without a git identity to derive one from.
AUTHOR_ENV = "CTX_JOURNAL_AUTHOR"
AUTHOR_MAX = 32
_SLUG_OK = "abcdefghijklmnopqrstuvwxyz0123456789"

# Resolving an author runs `git`, and `append` is called from an edit hook on
# every tool use. Cache per ledger root: the identity does not change inside a
# process's lifetime in any way worth two subprocesses per journalled event.
_AUTHOR_CACHE = {}


def today():
    return datetime.date.today().isoformat()


# --------------------------------------------------------------------------- #
# who is writing
# --------------------------------------------------------------------------- #

def author_key(layout):
    """The current author's journal file key. Slugified, filesystem-safe.

    Resolution order:

    1. `$CTX_JOURNAL_AUTHOR`, for a machine account or a CI identity.
    2. `git config user.email`, then `user.name`, read from the project the
       ledger belongs to — and only when that project really is a git work
       tree, because `git config` happily answers out of the user's *global*
       config from anywhere, which would attribute a ledger in a plain
       directory to whoever last configured git on the box.
    3. `""` — the documented fallback, and deliberately not a hostname, a
       username or a PID. With no git identity there is nothing to attribute
       an entry to that the repository does not already know, and inventing
       one would leak more than the commits in the repo do. An empty key means
       the entry goes to the unattributed stream, `journal/YYYY-MM-DD.md`,
       which is exactly the shape every pre-author entry already has. It is
       deterministic: the same unconfigured checkout always lands there, and
       nothing has to be merged back later.

    Never raises. A failure to identify the author must not stop the append.
    """
    try:
        override = _slug(os.environ.get(AUTHOR_ENV) or "")
        if override:
            return override
        root = layout.root.parent
        key = str(root)
        if key not in _AUTHOR_CACHE:
            _AUTHOR_CACHE[key] = _slug(_git_identity(root))
        return _AUTHOR_CACHE[key]
    except Exception:  # pragma: no cover - identity must never break a write
        return ""


def _slug(value):
    """ASCII, lowercase, `-`-separated, bounded. Empty when nothing survives.

    Truncation gets a hash tail rather than a bare cut, so two long addresses
    sharing a 32-character prefix do not silently share a journal file.
    """
    value = (value or "").strip()
    if not value:
        return ""
    out = []
    for char in value.lower():
        out.append(char if char in _SLUG_OK else "-")
    slug = "-".join(part for part in "".join(out).split("-") if part)
    if not slug:
        return ""
    if len(slug) > AUTHOR_MAX:
        digest = hashlib.sha256(value.encode("utf-8")).hexdigest()[:8]
        slug = slug[: AUTHOR_MAX - 9].rstrip("-") + "-" + digest
    return slug


def _looks_like_git_work_tree(root):
    """Cheap stat-only pre-filter, so the common case spawns no subprocess.

    An empty `.git` directory is not a repository, and asking `git` about one
    costs a process launch to be told so. `.git` as a *file* is a worktree or a
    submodule, which is a real work tree.
    """
    try:
        for candidate in [root, *root.parents]:
            marker = candidate / ".git"
            if marker.is_file():
                return True
            if marker.is_dir() and (marker / "HEAD").exists():
                return True
    except OSError:
        return False
    return False


def _git(root, *args):
    try:
        done = subprocess.run(
            ["git", "-C", str(root), *args],
            stdin=subprocess.DEVNULL, capture_output=True, text=True, timeout=5,
        )
    except (OSError, subprocess.SubprocessError):
        return ""
    return done.stdout.strip() if done.returncode == 0 else ""


def _git_identity(root):
    """`user.email`, else `user.name`, else `""`. Never raises."""
    if not _looks_like_git_work_tree(root):
        return ""
    if _git(root, "rev-parse", "--is-inside-work-tree") != "true":
        return ""
    for key in ("user.email", "user.name"):
        found = _git(root, "config", "--get", key)
        if found:
            return found
    return ""


def day_file(layout, day, author=None):
    """Where `day`'s entries by `author` live. Legacy shape when unattributed."""
    key = author_key(layout) if author is None else author
    if not key:
        return layout.journal_file(day)
    return layout.journal / f"{day}{AUTHOR_SEP}{key}.md"


